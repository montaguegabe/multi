"""Give Codex the sub-repo instructions it cannot discover on its own.

Codex assembles its instructions once per request from the project root (the
nearest ``.git``) down to the working directory, taking at most one file per
directory: ``AGENTS.override.md`` if present, else ``AGENTS.md``. It never
looks below the working directory, so a session started at the workspace root
never sees a sub-repo's ``AGENTS.md``.

``multi sync`` therefore writes a root ``AGENTS.override.md`` that embeds the
root ``AGENTS.md`` verbatim followed by one section per sub-repo instruction
file. Codex reads the override instead of ``AGENTS.md`` and gets everything.
Claude Code never reads ``AGENTS.override.md`` and already loads nested
instruction files on demand, so it is unaffected.

The root ``AGENTS.md`` is never modified. An ``AGENTS.override.md`` that multi
did not generate (no marker on its first line) is never replaced either; a
warning explains that the sub-repo instructions cannot be exposed until it is
moved aside. Re-check both tools' discovery rules when touching this: if Codex
starts reading nested ``AGENTS.md`` files, this module becomes redundant.
"""

import logging
from pathlib import Path

import click

from multi.cli_helpers import get_install_set_from_context
from multi.paths import Paths
from multi.repos import load_repos
from multi.sync_agents import would_generate_agents_for_repo

logger = logging.getLogger(__name__)

OVERRIDE_FILENAME = "AGENTS.override.md"
GENERATED_MARKER = "<!-- multi-generated: codex-override -->"
GENERATED_NOTICE = (
    "<!-- Generated by `multi sync`. Codex reads only one instruction file per "
    "directory and never looks into sub-repos, so this file repeats AGENTS.md and "
    "appends each sub-repo's own instructions. Edit those files, not this one; "
    "`multi sync` regenerates it. -->"
)
INSTRUCTION_FILENAMES = ("AGENTS.md", "CLAUDE.md")
# Codex's default `project_doc_max_bytes`; it truncates anything past this.
CODEX_DOC_BYTE_LIMIT = 32 * 1024
SETTINGS_KEY = "codexOverride"


def is_codex_override_enabled(paths: Paths) -> bool:
    """Enabled unless ``multi.json`` has ``"codexOverride": {"enabled": false}``."""
    settings = paths.settings.get(SETTINGS_KEY, {})
    if not isinstance(settings, dict):
        return True
    return bool(settings.get("enabled", True))


def override_path(paths: Paths) -> Path:
    return paths.root_dir / OVERRIDE_FILENAME


def is_generated_override(path: Path) -> bool:
    """Whether ``path`` is an override multi wrote (and may rewrite)."""
    if not path.is_file():
        return False
    with path.open("r", encoding="utf-8") as file:
        return file.readline().strip() == GENERATED_MARKER


def _instruction_file(directory: Path) -> Path | None:
    for filename in INSTRUCTION_FILENAMES:
        candidate = directory / filename
        if candidate.is_file():
            return candidate
    return None


def _repo_label(repo_path: Path, root_dir: Path) -> str:
    try:
        return repo_path.relative_to(root_dir).as_posix()
    except ValueError:
        return repo_path.name


def _sub_repo_sections(paths: Paths) -> list[tuple[str, Path]]:
    sections: list[tuple[str, Path]] = []
    for repo in load_repos(paths=paths):
        source = _instruction_file(repo.path)
        if source is not None:
            sections.append((_repo_label(repo.path, paths.root_dir), source))
    return sections


def build_codex_override(paths: Paths) -> str | None:
    """The override's content, or ``None`` when no sub-repo has instructions."""
    sections = _sub_repo_sections(paths)
    if not sections:
        return None

    lines = [GENERATED_MARKER, GENERATED_NOTICE, ""]
    root_file = _instruction_file(paths.root_dir)
    if root_file is not None:
        lines += [root_file.read_text(encoding="utf-8").rstrip(), ""]
    for label, source in sections:
        lines += [
            f"## Instructions for `{label}/`",
            "",
            f"The following applies when working on files under `{label}/`. "
            f"It is that repository's own `{source.name}`.",
            "",
            source.read_text(encoding="utf-8").rstrip(),
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def would_generate_codex_override(paths: Paths) -> bool:
    """Whether ``sync_all_codex`` will own the root override after this sync.

    Counts sub-repos whose instruction file does not exist yet but will be
    generated from ``AGENTS.parts`` later in the same sync.
    """
    if not is_codex_override_enabled(paths):
        return False
    target = override_path(paths)
    if target.exists() and not is_generated_override(target):
        return False
    if _sub_repo_sections(paths):
        return True
    return any(
        would_generate_agents_for_repo(repo.path, paths)
        for repo in load_repos(paths=paths)
        if repo.path.exists()
    )


def sync_all_codex(root_dir: Path, install_set: str | None = None) -> None:
    """Write the root ``AGENTS.override.md`` for Codex, never over user content."""
    paths = Paths(root_dir, install_set=install_set)
    if not is_codex_override_enabled(paths):
        logger.debug("Codex override generation is disabled")
        return

    target = override_path(paths)
    content = build_codex_override(paths)
    if content is None:
        if is_generated_override(target):
            target.unlink()
            logger.info(f"🗑️ Removed {OVERRIDE_FILENAME}: no sub-repo has instructions")
        return

    if target.exists() and not is_generated_override(target):
        logger.warning(
            f"⚠️  Cannot write {OVERRIDE_FILENAME}: the workspace has one that multi "
            "did not generate, so Codex will not see the sub-repo AGENTS.md "
            "instructions. Move its contents into AGENTS.md (or delete it) and "
            "rerun `multi sync`."
        )
        return

    size = len(content.encode("utf-8"))
    if size > CODEX_DOC_BYTE_LIMIT:
        logger.warning(
            f"⚠️  {OVERRIDE_FILENAME} is {size} bytes; Codex truncates instructions "
            f"past project_doc_max_bytes (default {CODEX_DOC_BYTE_LIMIT}). Shorten "
            "the instruction files or raise the limit in Codex config."
        )

    if target.is_file() and target.read_text(encoding="utf-8") == content:
        logger.debug(f"{OVERRIDE_FILENAME} is up to date")
        return
    target.write_text(content, encoding="utf-8")
    logger.info(f"✅ Generated {OVERRIDE_FILENAME} for Codex")


def codex_override_problem(paths: Paths) -> str | None:
    """A doctor warning when the override is missing, stale or not ours."""
    if not is_codex_override_enabled(paths):
        return None
    target = override_path(paths)
    expected = build_codex_override(paths)
    if target.exists() and not is_generated_override(target):
        if expected is None:
            return None
        return (
            f"{OVERRIDE_FILENAME} was not generated by multi, so Codex does not see "
            "the sub-repo AGENTS.md instructions. Move its contents into AGENTS.md "
            "and run `multi sync`."
        )
    if expected is None:
        if target.exists():
            return f"{OVERRIDE_FILENAME} is stale; run `multi sync` to remove it."
        return None
    if not target.is_file() or target.read_text(encoding="utf-8") != expected:
        return (
            f"{OVERRIDE_FILENAME} is missing or out of date with AGENTS.md and the "
            "sub-repo instruction files; run `multi sync`."
        )
    return None


@click.command(name="codex")
def sync_codex_cmd() -> None:
    """Generate root AGENTS.override.md so Codex sees sub-repo AGENTS.md files."""
    sync_all_codex(root_dir=Path.cwd(), install_set=get_install_set_from_context())
